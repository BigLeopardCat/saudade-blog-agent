import {build} from 'esbuild';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const check=process.argv.includes('--check');
async function publish(destination,source){
  if(check){
    if(await readFile(destination,'utf8')!==source)
      throw new Error(`Generated widget is stale: ${destination}; run npm run build`);
  }else{
    await mkdir(path.dirname(destination),{recursive:true});
    await writeFile(destination,source);
  }
}
for(const name of ['stream','protocol']){
  const result=await build({
    absWorkingDir:root,entryPoints:[`src/chat/${name}.${name==='protocol'?'ts':'js'}`],
    outfile:path.join(root,`public/live2d-widgets/chat-${name}.js`),
    bundle:true,write:false,format:'esm',platform:'browser',target:'es2022',minify:true,
    sourcemap:'linked',sourcesContent:true,legalComments:'inline',
    banner:{js:'// Generated by npm run build. Edit frontend/src/chat instead.'},
  });
  for(const file of result.outputFiles)await publish(file.path,file.text);
}
await publish(path.join(root,'public/live2d-widgets/licenses/eventsource-parser-LICENSE'),
  await readFile(path.join(root,'node_modules/eventsource-parser/LICENSE'),'utf8'));
