def main() -> int:
    bad = 0
    for row in CASES:
        expect, cid, desc, text = row[0], row[1], row[2], row[3]
        fails = judge(cid, text, frames=(row[4] if len(row) > 4 else None))
        got = "FAIL" if fails else "PASS"
        mark = "✓" if got == expect else "✗ 不符"
        if got != expect:
            bad += 1
        print(f"{mark} [{cid}] {desc}\n    期望 {expect} / 实得 {got} {fails if fails else ''}")
    print(f"\n=== {'全部符合预期' if bad == 0 else f'{bad} 项不符'} ===")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
