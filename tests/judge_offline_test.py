def _split_top(s: str) -> list[str]:
    out, depth, cur = [], 0, ""
    i = 0
    while i < len(s):
        if s.startswith("(?:", i):
            depth += 1; cur += "(?:"; i += 3; continue
        c = s[i]
        if c == ")" and depth:
            depth -= 1
        elif c == "|" and not depth:
            out.append(cur); cur = ""; i += 1; continue
        cur += c; i += 1
    out.append(cur)
    return out


def _expand_branch(b: str) -> list[str]:
    res, i, out = [""], 0, []
    while i < len(b):
        if b.startswith("(?:", i):
            depth, j = 1, i + 3
            while j < len(b) and depth:
                if b.startswith("(?:", j):
                    depth += 1; j += 3
                elif b[j] == ")":
                    depth -= 1; j += 1
                else:
                    j += 1
            inner = b[i + 3: j - 1]
            opt = b[j: j + 1] == "?"
            alts = [x for a in _split_top(inner) for x in _expand_branch(a)]
            if opt:
                alts.append("")
            res = [r + a for r in res for a in alts]
            i = j + (1 if opt else 0)
        else:
            res = [r + b[i] for r in res]
            i += 1
    return res


def _leaf_forms(frag: str) -> list[str]:
    return [x for b in _split_top(frag) for x in _expand_branch(b)]


