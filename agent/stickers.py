# -*- coding: utf-8 -*-
"""贴纸记号的确定性修补（20261002）：把"只写了开头冒号"的残记号补回 `:名字:`。

## 为什么有这一层

贴纸的渲染契约在前端是**两个冒号**：`/:([^:\\s]{1,12}):/g`（看板娘 fallback
`frontend/public/live2d-widgets/chat-render.js` 与站内 markdown 插件
`frontend/src/utils/stickers.ts` 各一份，逐字同形）。缺收尾冒号的记号**结构上匹配不上**，
而两个渲染器都按"未命中名字原样保留成文本"处理 ⇒ 主人读到的是一段裸露的 `:头疼`。

模型偶尔就写残（实测：`logs/agent/traces/20261002/` 的 `20261002T211008_5_r97d4db1.json`
「…杂鱼真是麻烦呢～ :头疼\n\n虽然…」与 `20261002T212117_5_r8eb7dfd.json` 的 `:生气\n\n`；
同期 57 份 trace 里只有这 2 份、其余 24 份写的是完整的 `:比耶:` / `:震惊:`）。agent 侧
此前对贴纸**零处理**：正文原样发出，这一层是唯一一处会碰它的地方。

**为什么是确定性修补而不是"再在提示词里加一句"**：模型写残的概率不会因为多一句纪律
归零（提示词已经写着格式与例子），而残记号的后果是确定的（渲染不出来、还留一行废话）。
修补只做一件事——**给已知名字的残记号补上收尾冒号**，不猜意图、不删文本。

## 边界（宁漏勿误伤，与渲染器的排除规则同源）

  · 只认**登记在册的 8 个名字**（`STICKER_NAMES`，与前端两处清单三处同步，由
    `tests/test_sticker_repair.py` 逐处核对）。表外的 `:开心` / `:smile:` 一个字都不动
    ——渲染器本来就不认它们，改了反而把"文本原样"这条既定行为弄坏。
  · **只认 ASCII 冒号开场**：中文正文里的全角冒号大量是句读（"原因：头疼"），补一个
    收尾冒号会把一句正常的话变成一张贴纸图。全角开场一律不碰。
  · 名字后面**必须不是接续字符**：`:头疼啊` / `:比耶2` 不动——那是词的一部分，不是记号。
    只补后面跟着空白、标点或行尾的那些（实测残记号的形态正是 `:头疼\n`）。
  · **围栏代码块与行内代码一律跳过**：渲染器也不在那里面替换（`:xx:` 在代码里就是文本），
    在这里替换会让"代码里的记号被吃掉"——比不修更坏。
  · 幂等：已经完整的 `:头疼:` 不会被补成 `:头疼::`。
"""
import re

# 名字清单 = 前端渲染契约。三处同源：
#   · 本站 markdown 插件 `frontend/src/utils/stickers.ts::STICKERS`（父仓）
#   · 看板娘 fallback 渲染器 `frontend/public/live2d-widgets/chat-render.js` 的内联清单（本仓）
#   · `agent/prompts.py::STICKER_GUIDE` 写给模型的那份说明（散文，无法机器核对）
# 增删名字要三处一起改；`tests/test_sticker_repair.py` 会拿前两处逐字核对这一元组。
STICKER_NAMES = ("头疼", "委屈", "害羞", "比耶", "犯错", "生气", "贴贴", "震惊")

# 残记号 = 词边界上的 `:` + 已知名字 + **不是接续字符**。
#   · 前面的 `(?<!\w)`：排掉"原因:头疼"这类**句读冒号**——ASCII 冒号跟在汉字后面时
#     是正文的一部分，补一个收尾冒号会把一句正常的话变成一张贴纸图（`\w` 在 Python 3
#     里是 Unicode 的，汉字算词字符，这一条因此同时挡住"汉字+冒号"的形态）；
#     实测那两条残记号前面都是空格（「麻烦呢～ :头疼」），不受影响。
#   · 末尾的 lookahead：`:：` 排掉已写全的记号（幂等，`:头疼:` 不会变成 `:头疼::`）、
#     `\w`（含汉字）排掉 `:头疼啊` / `:比耶2` —— 那是词的一部分，不是记号。
_UNCLOSED_RE = re.compile(
    r"(?<!\w):(" + "|".join(STICKER_NAMES) + r")(?![\w:：])")


def repair_sticker_tokens(text: str) -> str:
    """把已知名字的残记号 `:头疼` 补成 `:头疼:`；其余一个字不动。

    返回**新串**（调用方自己比对是否变过，变了才留痕）。
    """
    if not text or ":" not in text:
        return text
    out: list[str] = []
    for i, block in enumerate(text.split("```")):
        if i % 2:                      # 围栏代码块内：渲染器不替换，这里也不动
            out.append(block)
            continue
        # 段内再按行内代码切：奇数段是 `` `…` `` 里的内容，原样；偶数段才做修补。
        # **两层的分隔符各归各**（这里用 "`" 拼回、外层才用 "```"）——串了会把
        # "`` `a` ``" 拼成 "`` ```a``` ``"（改坏正文，20261002 本套件第 ② 组当场抓到）。
        parts = block.split("`")
        for j, seg in enumerate(parts):
            parts[j] = seg if j % 2 else _UNCLOSED_RE.sub(
                lambda m: f":{m.group(1)}:", seg)
        out.append("`".join(parts))
    return "```".join(out)
