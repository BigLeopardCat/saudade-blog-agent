# 本循环的引言（替代生产那句"你是回复者，不是执行者"，也替代原来那 886 字的
# `_DISCIPLINE_STANCE`）。**这是臂上唯一一处"立场"声明**，一句话说完。
_LOOP_DISCIPLINE_INTRO = """\
叙述纪律（本循环里你**既是决策者也是回复者**，工具就在你手上——下面这些是**回复**
那一半的纪律，除已按本循环裁掉的几条外**逐条照旧生效**，一条都不放宽）："""


def _split_narrator_discipline() -> tuple[str, dict[int, str], str]:
    """把 `NARRATOR_DISCIPLINE` 切成 (引言, {条号: 正文}, 尾注)。

    **现场切、不抄第二份**：抄一份正文进臂的常量，就多一个"生产改了臂不跟着改"的
    漂移源，而那种漂移没有判据看得见（本仓点名的失效模式）。尾注 = 末条之后那一段
    （`[执行计划]（…）` 那行表头）——本循环没有那一格，臂版整段不要。
    """
    text = NARRATOR_DISCIPLINE
    marks = list(re.finditer(r"(?m)^(\d{1,2})\. ", text))
    if not marks:
        raise RuntimeError("NARRATOR_DISCIPLINE 里一条编号纪律都没切出来——切法失效了")
    intro = text[:marks[0].start()]
    rules: dict[int, str] = {}
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        rules[int(m.group(1))] = text[m.start():end]
    # 尾注：末条正文里最后那个 `[执行计划]…` 表头（它在末条之后、与纪律无关）
    last = rules[max(rules)]
    cut = last.find("\n[执行计划]")
    tail = ""
    if cut >= 0:
        tail = last[cut + 1:]
        rules[max(rules)] = last[:cut + 1]
    return intro, rules, tail


def narrator_discipline_loop() -> str:
    """循环臂读的那一份叙述纪律（见本段头注：按条裁，不是"接整份 + 作废"）。"""
    _intro, rules, _tail = _split_narrator_discipline()
    out = [_LOOP_DISCIPLINE_INTRO]
    for n in sorted(rules):
        if n in NARRATOR_DISCIPLINE_LOOP_OVERRIDES:
            repl = NARRATOR_DISCIPLINE_LOOP_OVERRIDES[n]
            if repl:
                out.append(repl)
        else:
            out.append(rules[n])
    return "\n".join(out)


# 建一次、当常量用（纯函数、无副作用；三条臂都读这一格，别再各自调一次）。
NARRATOR_DISCIPLINE_LOOP = narrator_discipline_loop()
