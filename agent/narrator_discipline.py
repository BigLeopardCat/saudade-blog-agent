"""叙述纪律的**循环臂版**（20261021）：同一份纪律里，哪几条在 ReAct 循环里算数。

## 这份东西为什么单独一个模块

生产那份纪律（`agent.prompts.NARRATOR_DISCIPLINE`）是**narrator 节点**的——那个节点
零工具、只把系统的执行记录说成人话。`agent/react_arm.py` / `agent/tools_arm.py` /
`agent/capability_arm.py` 三条臂**把它整份接了过来**，再在前面挂一段 886 字的
`_DISCIPLINE_STANCE` 逐条作废其中前提为假的那几条。于是一条调用里同时出现「你没有
工具」和「你有工具、自己调用」两句相反的话，靠第三段裁定哪句算数。**补丁叠补丁，
没有一条退场过**——这是"照着事故加一条、每条臂后来才出现、接的时候整份照搬、再补一层
作废声明"那套累积法长出来的形状。

这一模块是那条路的替代：**按条裁**。前提为假的、纯风格的、已经搬了家的那些条
**根本不进臂的提示词**；留下的条**逐字取自**生产那一份（现场切，不抄第二份）。

## 为什么不住在 `prompts.py` 里

`prompts.py` 是**生产提示词正文**的家（12 个常量、856 行，已在台账上）。这一层是
**臂的适配**——"这份生产资产里哪几条对这条循环成立"——与正文不是同一件事，改它的
理由也完全不同（一个是"生产出了事故"，一个是"这条臂的前提变了"）。住在一起会让
两边互相带着漂移，且 `prompts.py` 当场超台账（实测 +147 行 / +3 定义）。

## 判据

`tests/test_narrator_discipline_loop.py`（四组 + 反控实测各红）：

  · **机械关系**：留条集合 == 生产纪律的条号 − `NARRATOR_DISCIPLINE_LOOP_OVERRIDES`，
    且留条正文**逐字**等于生产那一条（生产改了这边跟着改；改动生产任意一条正文 ⇒
    反控红）；
  · **两张理由表**：**动过的**（裁掉 / 改写）每一条都要写为什么（`_LOOP_DROP_REASONS`），
    **故意原样留着的**每一条也要写为什么（`_LOOP_KEEP_REASONS`）——**这是防再累积的那
    一格**：纪律集合往任一方向动一下，都必须先在这里写下理由，否则红；
  · **成品**：前提为假的那几条一个都不许出现；诚实那半句（3 与 18）在；
  · **生产那一份一个字节都没动**（sha256 与拆段前一致）——本模块只加不改。

## ⚠️ 为什么还留着一档"故意不动"（`_LOOP_KEEP_REASONS`）

那八条（2 引用不许编造 / 4 台账 / 5 ERROR 帧 / 7 链接 / 11 复读 / 14 帧封顶 /
16 站内"有没有" / 21 pending_action）今天的守卫是 `graph.gate_node` 的**闸门替换**：
模型**仍然说得出**，闸门拦下之后把**整段回复**换成道歉。那不是"结构上不可能"，是
"拿一次回复换一次拦截"——**删掉提示词那一句 ⇒ 拦截次数上升 ⇒ 主人偶尔收到一句道歉
而不是一句实话**。提示词是便宜的那条路，闸门是兜底。

这一档**不是"历史资产"，是待裁清单**：每一条都记着"守卫是什么、读数看哪一族"，A/B
跑完拿着那一族的红数就能逐条裁决。其中 4 与 14 的守卫是**结构**而不是闸门替换
（`frame_excerpt` 自己产那条注记、三族 denial 判据读的是台账本身），所以它们更接近
"真已被解决"——读数一到就该先动这两条。

`_LOOP_KEEP_REASONS` 与 `tests/test_narrator_discipline_loop.py` 的 `_GATE_BACKSTOPPED`
是**两处记录**：单向差集必须为空（改一处不改另一处 ⇒ 红）。
"""

