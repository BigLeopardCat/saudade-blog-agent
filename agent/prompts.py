def audience_block(role: str | None) -> str:
    """本轮对话者是谁 → 注入 narrator 的段落（确定性，无 LLM）。

    未知角色（role=None，未登录/身份不明）走**访客**那段：fail-closed 的方向是
    "别把人当主人"——把访客认成主人 = 用主人的口径答权限相关的事。

    判据是**管理员族**（`ADMIN_ROLES`，20260926 起含超级管理员）而不是
    `role == "admin"`：写死字面量的那天，uid=1 提权成超管后拿到的是**访客人设**
    （"以访客的口径答权限相关的事"），而这条错法完全静默。

    杂鱼（20261002）走第一支：`CHAT_ONLY_ROLES` 与 `ADMIN_ROLES` 不重叠，顺序不影响
    结果，但放在前面读起来更直白（它是一个更窄的判据）。`role=None` 落到最后一支
    ——**身份不明仍然是访客**，这条 fail-closed 方向没有被新分支吃掉。
    """
    from agent.principal import ADMIN_ROLES, CHAT_ONLY_ROLES
    if role in CHAT_ONLY_ROLES:
        return AUDIENCE_ZAKO
    return AUDIENCE_ADMIN if role in ADMIN_ROLES else AUDIENCE_VISITOR

